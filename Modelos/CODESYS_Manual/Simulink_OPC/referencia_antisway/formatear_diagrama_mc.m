function formatear_diagrama_mc(model)
% Disposicion compacta; no cambia conexiones ni parametros del control.
sub=[model '/Motion Controller'];
ann=find_system(sub,'SearchDepth',1,'FindAll','on','Type','annotation');
for j=1:numel(ann),delete(get_param(ann(j),'Object'));end
positions={ ...
 'Sensors',[30 90 60 110];'References',[30 340 60 360]; ...
 'Commands',[30 390 60 410];'Drive Feedback',[30 440 60 460]; ...
 'Parameters',[220 530 320 570];'Estimadores',[220 80 400 160]; ...
 'MC Carro',[560 100 760 280];'MC Izaje',[560 350 760 470]; ...
 'Diagnosticos',[850 520 990 580]; ...
 'T_hm*',[1100 370 1130 390];'T_tmcontrolador',[1100 110 1130 130]; ...
 'SW aplicada comun',[1100 180 1130 200];'Estados carro',[1100 260 1130 280]; ...
 'Estados izaje',[1100 310 1130 330];'Diagnosticos carro',[1100 520 1130 540]; ...
 'Diagnosticos izaje',[1100 590 1130 610]};
for j=1:size(positions,1),set_param([sub '/' positions{j,1}],'Position',positions{j,2});end
ll=find_system(sub,'SearchDepth',1,'FindAll','on','Type','line');
Simulink.BlockDiagram.routeLine(ll);
set_param(sub,'ZoomFactor','FitSystem');
end
